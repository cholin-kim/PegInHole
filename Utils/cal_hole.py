def cal_h2h(id_from, id_to):
    mtx_h2o = cal_o2h(id_from)
    mtx_h2o = np.linalg.inv(mtx_h2o)

    mtx_o2h = cal_o2h(id_to)

    return np.matmul(mtx_h2o, mtx_o2h)
